/**
 * Generates NEEDS_VERIFICATION.md from src/data/players.ts.
 *
 * Runs automatically on `npm run build` (via prebuild) and on demand with
 * `npm run verify`. esbuild ships with Vite, so there is no extra dependency.
 */
import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

const result = await build({
  entryPoints: [resolve(root, 'src/data/players.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  write: false,
  logLevel: 'silent',
})

const code = result.outputFiles[0].text
const mod = await import(
  `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`
)
const players = mod.PLAYERS

const SPORTS = [
  ['mlb', 'Baseball'],
  ['nba', 'Basketball'],
  ['nfl', 'American football'],
  ['soccer', 'Soccer'],
]

const ERAS = [
  ['Pre-1980', (s) => s < 1980],
  ['1980-1999', (s) => s >= 1980 && s < 2000],
  ['2000-2014', (s) => s >= 2000 && s < 2015],
  ['2015-present', (s) => s >= 2015],
]

const usd = (n) =>
  `$${n.toLocaleString('en-US', { maximumFractionDigits: 0 })}`

const low = players.filter((p) => p.confidence === 'low')
const medium = players.filter((p) => p.confidence === 'medium')
const high = players.filter((p) => p.confidence === 'high')
const missingAvg = players.filter((p) => p.leagueAvgThatSeason === null)

const lines = []
const w = (s = '') => lines.push(s)

w('# NEEDS_VERIFICATION')
w()
w('_Generated by `npm run verify`. Do not edit by hand — edit `src/data/players.ts`._')
w()
w(
  `**${players.length} entries on file.** ` +
    `${high.length} high confidence, ${medium.length} medium, ${low.length} low.`,
)
w()
w('## What the confidence ratings mean')
w()
w('| Rating | Meaning |')
w('| --- | --- |')
w(
  '| `high` | Published contract or salary figure that is documented in multiple places and not seriously disputed. |',
)
w(
  '| `medium` | Sourced to a salary database (Baseball-Reference, Basketball-Reference, Spotrac, the MLS Players Association) or derived from a well-documented contract total. Reliable enough to play on, worth spot-checking. |',
)
w(
  '| `low` | Press estimate, reconstructed from a contract total, converted from a foreign currency, or otherwise contested. **Every entry below needs a real source before launch.** |',
)
w()
w('The dev panel (`?dev=1`) has a "verified data only" toggle that excludes every')
w('`low` entry from the daily selection, so the game is playable on checked data')
w('while the rest is being worked through.')
w()

w('## Coverage')
w()
w('| Sport | Total | Pre-1980 | 1980-1999 | 2000-2014 | 2015-present | Low conf. |')
w('| --- | ---: | ---: | ---: | ---: | ---: | ---: |')
for (const [sport, label] of SPORTS) {
  const set = players.filter((p) => p.sport === sport)
  const cells = ERAS.map(([, test]) => set.filter((p) => test(p.season)).length)
  const lows = set.filter((p) => p.confidence === 'low').length
  w(`| ${label} | ${set.length} | ${cells.join(' | ')} | ${lows} |`)
}
w()

w('## Entries needing verification')
w()
if (low.length === 0) {
  w('_None._')
} else {
  for (const [sport, label] of SPORTS) {
    const set = low.filter((p) => p.sport === sport)
    if (set.length === 0) continue
    w(`### ${label} (${set.length})`)
    w()
    for (const p of set.sort((a, b) => a.season - b.season)) {
      w(`#### ${p.name} — ${p.team}, ${p.season}`)
      w()
      w(`- **Figure used:** ${usd(p.salaryUSD)}`)
      w(`- **What to check:** ${p.source}`)
      w(`- **Entry id:** \`${p.id}\``)
      w()
    }
  }
}

w('## Known systemic issues')
w()
w(
  '1. **`leagueAvgThatSeason` is approximate throughout.** These are league-wide means ' +
    'assembled from union figures and press summaries, rounded, and in some cases ' +
    'interpolated between published years. They are surfaced in the UI as "approx." ' +
    'and drive the in-game hint, so a wrong one makes a puzzle unfairly hard rather ' +
    `than merely inaccurate. ${missingAvg.length} entries have no figure at all (\`null\`).`,
)
w()
w(
  '2. **Soccer wages are conversions, not salaries.** Every European entry started as a ' +
    'weekly figure in GBP or EUR, was annualised, and was converted at an approximate ' +
    'period exchange rate. Several are net-of-tax figures grossed up by estimate. None ' +
    'is rated above `medium`, and the MLS/NWSL entries — where the players\' union ' +
    'publishes actual contracts — are the only soccer figures worth trusting.',
)
w()
w(
  '3. **Pre-1980 figures across all sports are press estimates.** Before free agency and ' +
    'players\' unions, salaries were private and reported second-hand. Where two ' +
    'accounts disagree, the more widely repeated figure is used and the entry is rated ' +
    'down.',
)
w()
w(
  '4. **NFL "salary" is ambiguous by construction.** Base salary, cash earned, and cap ' +
    'hit can differ by an order of magnitude in the same season. This file uses cash ' +
    'earned where it is known and base salary otherwise, and says which in `source`. ' +
    'Rookie-contract entries look tiny because the signing bonus was paid in a ' +
    'different year — that is real, not an error.',
)
w()
w(
  '5. **Contract AAV is not a season salary.** Entries derived from a multi-year total ' +
    '(Reggie Jackson 1977, Catfish Hunter 1975, Pete Maravich 1970, and others) use the ' +
    'annual average value. The actual season-by-season payments were usually uneven.',
)
w()

w('## Deliberately excluded')
w()
w(
  '- Cristiano Ronaldo at Al Nassr, and other Saudi Pro League deals. The reported ' +
    'figures bundle salary, image rights and state promotional contracts, and no ' +
    'breakdown is public.',
)
w(
  '- Any player whose salary could only be sourced to a listicle or an aggregator with ' +
    'no primary reference.',
)
w()
w(`_Last generated ${new Date().toISOString().slice(0, 10)}._`)

await writeFile(resolve(root, 'NEEDS_VERIFICATION.md'), lines.join('\n') + '\n', 'utf8')
console.log(
  `NEEDS_VERIFICATION.md written — ${players.length} entries, ${low.length} flagged low.`,
)
